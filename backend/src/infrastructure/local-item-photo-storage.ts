import { randomUUID } from 'node:crypto';
import { lstat, mkdir, open, realpath, unlink, readFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, parse } from 'node:path';
import type { ItemPhotoStorage, NormalizedItemPhoto, PhotoReference } from '../application/item-photos.js';

const referencePattern = /^items\/[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.webp$/;

/** One instance per creation operation. Root is private and outside repositories. */
export class LocalItemPhotoStorage implements ItemPhotoStorage {
  private attemptedSave = false;
  private generatedReference: PhotoReference | undefined;
  constructor(
    private readonly root: string,
    private readonly hasReferences: (reference: PhotoReference) => Promise<boolean>,
  ) {
    if (!isAbsolute(root)) throw new Error('Photo root must be absolute');
  }

  private async directory(): Promise<string> {
    // Resolve existing ancestor first; reject roots inside any Git checkout.
    let ancestor = this.root;
    while (true) {
      try { await realpath(ancestor); break; }
      catch (error) {
        if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
        const parent = dirname(ancestor);
        if (parent === ancestor) throw error;
        ancestor = parent;
      }
    }
    let current = await realpath(ancestor);
    while (true) {
      try { await lstat(join(current, '.git')); throw new Error('Photo root cannot be inside a repository'); }
      catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
      if (current === parse(current).root) break;
      current = dirname(current);
    }
    await mkdir(this.root, { recursive: true, mode: 0o700 });
    const canonicalRoot = await realpath(this.root);
    // Fail closed on links; configured root and items are application-owned.
    if ((await lstat(this.root)).isSymbolicLink()) throw new Error('Linked photo root is forbidden');
    const directory = join(canonicalRoot, 'items');
    await mkdir(directory, { recursive: true, mode: 0o700 });
    if ((await lstat(directory)).isSymbolicLink()) throw new Error('Linked photo directory is forbidden');
    return directory;
  }

  async save(photo: NormalizedItemPhoto): Promise<PhotoReference> {
    if (photo.format !== 'webp') throw new Error('Only normalized WebP can be stored');
    // One photo belongs to one operation, including failed attempts.
    if (this.attemptedSave) throw new Error('Photo storage operation already used');
    this.attemptedSave = true;
    const directory = await this.directory();
    const reference = 'items/' + randomUUID() + '.webp';
    const path = join(directory, reference.slice(6));
    const handle = await open(path, 'wx', 0o600);
    try {
      await handle.writeFile(photo.bytes);
      await handle.sync();
      await handle.close();
      this.generatedReference = reference;
      return reference;
    } catch (error) {
      await handle.close().catch(() => {});
      // Even a partial write is kept if persisted-reference checks are uncertain.
      try {
        if (await this.hasReferences(reference) === false) await unlink(path);
      } catch {
        // Preserve the original write error. A private orphan can be reviewed later.
      }
      throw error;
    }
  }

  /** Reads only a generated, referenced normalized photo; never a caller path. */
  async readReferenced(reference: PhotoReference): Promise<NormalizedItemPhoto | null> {
    if (!referencePattern.test(reference)) return null;
    if (await this.hasReferences(reference) !== true) return null;
    const directory = await this.directory();
    const path = join(directory, reference.slice(6));
    try {
      const stat = await lstat(path);
      if (!stat.isFile() || stat.isSymbolicLink() || stat.size > 10_000_000) throw new Error('Unsafe stored photo');
      const bytes = await readFile(path);
      if (bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP') {
        throw new Error('Stored photo is not normalized WebP');
      }
      return { format: 'webp', bytes };
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw error;
    }
  }

  async removeIfUnreferenced(reference: PhotoReference): Promise<void> {
    if (!referencePattern.test(reference)) throw new Error('Invalid photo reference');
    if (reference !== this.generatedReference) throw new Error('Photo was not generated by this operation');
    const directory = await this.directory();
    const referenced = await this.hasReferences(reference);
    if (referenced !== false) throw new Error('Photo still referenced or reference check uncertain');
    const path = join(directory, reference.slice(6));
    try {
      if ((await lstat(path)).isSymbolicLink()) throw new Error('Linked photo is forbidden');
      await unlink(path);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }
  }
}
